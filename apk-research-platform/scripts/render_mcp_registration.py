"""Render the DSH NEXT MCP registration for this checkout.

The DSH MCP client is registered through a Cordis patch entry. Absolute paths are
host specific, so they are generated here instead of being hand-edited: run this
script after moving the checkout, then paste the printed snippet into the DSH
profile patch (or install the generated bundle directory with plugin_manager).

Outputs
-------
config/dsh-mcp.registration.yml   copy/paste snippet for <DSH_HOME>/profiles/<p>/cordis.patch.yml
dsh-plugin/cordis.patch.yml       config-only bundle patch (same entry, installable)
dsh-plugin/package.json           bundle manifest for plugin_manager

Usage
-----
    .venv/Scripts/python.exe scripts/render_mcp_registration.py
    .venv/Scripts/python.exe scripts/render_mcp_registration.py --server-name apkplat --scope '*'
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PYTHON = ROOT / ".venv" / "Scripts" / "python.exe"
SERVER = ROOT / "mcp-server" / "mcp_server" / "server.py"
STORAGE = ROOT / "storage"


def _q(value: str) -> str:
    """Quote a YAML scalar; Windows paths stay readable in single quotes."""
    return "'" + value.replace("'", "''") + "'"


def render(server_name: str, projects: str, actor: str, timeout_ms: int) -> str:
    lines = [
        "- insert:",
        "    - id: apkplat-mcp",
        "      name: '@deepseek-ai/dsh-mcp-client'",
        "      config:",
        f"        serverName: {server_name}",
        "        transport: stdio",
        f"        command: {_q(str(PYTHON))}",
        "        args:",
        f"          - {_q(str(SERVER))}",
        f"        cwd: {_q(str(ROOT))}",
        "        env:",
        f"          APKPLAT_STORAGE: {_q(str(STORAGE))}",
        f"          APKPLAT_MCP_PROJECTS: {_q(projects)}",
        f"          APKPLAT_MCP_ACTOR: {_q(actor)}",
        "          PYTHONUTF8: '1'",
        "          PYTHONIOENCODING: 'utf-8'",
        f"        toolCallTimeoutMs: {timeout_ms}",
        "        failOnStartupError: true",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server-name", default="apkplat", help="MCP namespace ([A-Za-z0-9_-]{1,32})")
    parser.add_argument("--scope", default="*", help="comma separated project ids the server may touch")
    parser.add_argument("--actor", default="dsh-agent", help="actor recorded in the audit trail")
    parser.add_argument("--timeout-ms", type=int, default=120000, help="per tools/call timeout")
    args = parser.parse_args(argv)

    if not SERVER.exists():
        raise SystemExit(f"missing MCP server: {SERVER}")
    if not PYTHON.exists():
        raise SystemExit(f"missing virtual environment interpreter: {PYTHON}")

    patch = render(args.server_name, args.scope, args.actor, args.timeout_ms)

    config_dir = ROOT / "config"
    config_dir.mkdir(parents=True, exist_ok=True)
    snippet = config_dir / "dsh-mcp.registration.yml"
    snippet.write_text(
        "# generated by scripts/render_mcp_registration.py - paste under the top-level\n"
        "# list of <DSH_HOME>/profiles/<profile>/cordis.patch.yml, then restart DSH NEXT\n"
        "# or reload the profile. Tools appear as mcp__<serverName>__<tool>.\n\n" + patch,
        encoding="utf-8",
    )

    bundle = ROOT / "dsh-plugin"
    bundle.mkdir(parents=True, exist_ok=True)
    (bundle / "cordis.patch.yml").write_text(patch, encoding="utf-8")
    manifest = {
        "name": "@local/apkplat-mcp",
        "version": "1.0.0",
        "private": True,
        "type": "module",
        "files": ["cordis.patch.yml", "README.md"],
        "dsh": {"bundle": {"patch": "./cordis.patch.yml"}},
    }
    (bundle / "package.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(snippet)
    print(patch)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
